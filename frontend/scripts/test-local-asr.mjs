import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { createServer } from 'vite';
import { existsSync, mkdirSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const frontend = dirname(dirname(fileURLToPath(import.meta.url)));
const assessmentPrompt = readFileSync(resolve(frontend, '../docs/local-asr-assessment-prompt.md'), 'utf8');
const setupPrompt = readFileSync(resolve(frontend, '../docs/local-asr-agent-prompt.md'), 'utf8');
const server = await createServer({ root: frontend, server: { host: '127.0.0.1', port: 0 }, logLevel: 'error' });
await server.listen();
const port = server.httpServer.address().port;
const executablePath = ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync);
const browser = await chromium.launch({ headless: true, executablePath, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const output = resolve(frontend, '../artifacts/local-asr-ui');
mkdirSync(output, { recursive: true });
try {
  for (const skin of ['starlake', 'crabapple']) {
    const page = await browser.newPage({ viewport: { width: 1366, height: 900 } });
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.addInitScript(() => {
      window.testClipboard = '';
      Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async (text) => { window.testClipboard = text; } } });
    });
    await page.goto(`http://127.0.0.1:${port}/?skin=${skin}&state=normal&records=2`);
    await page.waitForFunction(() => document.body.dataset.appReady === 'true');
    await page.click('.settings-button');
    await page.locator('#speech-provider').waitFor();
    assert.equal(await page.locator('#speech-provider').inputValue(), 'dashscope');
    assert.equal(await page.locator('#local-speech-fields').isVisible(), false);
    const cloudModel = await page.locator('#speech-model').inputValue();
    const cloudEndpoint = await page.locator('#speech-endpoint').inputValue();
    await page.selectOption('#speech-provider', 'local');
    assert.equal(await page.locator('#cloud-speech-fields').isVisible(), false);
    assert.equal(await page.locator('#local-speech-endpoint').inputValue(), 'ws://127.0.0.1:8765/asr');
    assert.match(await page.locator('#local-model-info').innerText(), /实际模型尚未确认/);
    assert.match(await page.locator('#local-model-info').innerText(), /default 不是模型名称/);
    assert.equal(await page.locator('.local-model-option').count(), 3);
    for (const id of ['paraformer-streaming-int8', 'qwen3-asr-0.6b', 'qwen3-asr-1.7b']) {
      const card = page.locator(`.local-model-option[data-model-id="${id}"]`);
      await card.locator('[data-action="copy-model-assessment"]').click();
      await page.waitForFunction((id) => window.testClipboard.startsWith('# 圈说本地语音 · 第一阶段') && window.testClipboard.includes(`登记 ID：${id}`), id);
      assert.equal(await page.evaluate(() => window.testClipboard.startsWith('# 圈说本地语音 · 第一阶段')), true);
      assert.equal((await page.evaluate(() => window.testClipboard)).startsWith(assessmentPrompt), true);
      assert.match(await page.evaluate(() => window.testClipboard), new RegExp(`登记 ID：${id.replaceAll('.', '\\.')}`));
      assert.match(await page.evaluate(() => window.testClipboard), /只读检测，不下载、安装、启动或加载模型/);
      assert.match(await page.evaluate(() => window.testClipboard), /用简短的人话告诉我结论，不安装/);
      await card.locator('[data-action="copy-model-setup"]').click();
      await page.waitForFunction((id) => window.testClipboard.startsWith('# 圈说本地语音 · 第二阶段') && window.testClipboard.includes(`登记 ID：${id}`), id);
      assert.equal((await page.evaluate(() => window.testClipboard)).startsWith(setupPrompt), true);
      assert.match(await page.evaluate(() => window.testClipboard), new RegExp(`登记 ID：${id.replaceAll('.', '\\.')}`));
      assert.match(await page.evaluate(() => window.testClipboard), /保留其他模型与当前选择/);
      assert.match(await page.evaluate(() => window.testClipboard), /不要求方案摘要或逐步确认/);
      assert.equal(await card.locator('[data-action="switch-local-model"]').isDisabled(), id !== 'paraformer-streaming-int8');
    }
    assert.match(await page.locator('#local-model-recommendations').innerText(), /初步预留估算/);
    await page.locator('#local-model-info').scrollIntoViewIfNeeded();
    await page.screenshot({ path: resolve(output, `${skin}-model-choices.png`) });
    assert.match(await page.locator('#connection-result').innerText(), /不打开麦克风/);
    await page.fill('#local-speech-endpoint', 'ws://127.0.0.1:9012/asr');
    await page.fill('#local-speech-model', 'my-low-memory-model');
    await page.click('[data-action="copy-local-assessment"]');
    await page.waitForFunction(() => window.testClipboard.startsWith('# 圈说本地语音 · 第一阶段'));
    assert.equal(await page.evaluate(() => window.testClipboard), assessmentPrompt);
    assert.match(await page.evaluate(() => window.testClipboard), /当前可用显存/);
    await page.locator('[data-action="copy-local-assessment"]').scrollIntoViewIfNeeded();
    await page.screenshot({ path: resolve(output, `${skin}-prompts.png`) });
    await page.click('[data-action="copy-local-prompt"]');
    await page.waitForFunction(() => window.testClipboard.startsWith('# 圈说本地语音 · 第二阶段'));
    assert.equal(await page.evaluate(() => window.testClipboard), setupPrompt);
    assert.match(await page.evaluate(() => window.testClipboard), /quanshuo-asr-v1/);
    assert.match(await page.evaluate(() => window.testClipboard), /--smoke-local-asr/);
    await page.click('[data-action="test"]');
    await page.waitForSelector('#connection-result[data-state="ok"]');
    assert.match(await page.locator('#connection-result').innerText(), /未验证实际模型/);
    assert.match(await page.locator('#local-model-info').innerText(), /Paraformer 中英双语/);
    assert.match(await page.locator('#local-model-info').innerText(), /0 GB/);
    assert.match(await page.locator('#local-model-info').innerText(), /上次测试/);
    await page.locator('#local-model-info').scrollIntoViewIfNeeded();
    await page.screenshot({ path: resolve(output, `${skin}-model-info.png`) });
    await page.locator('.settings-view [data-action="back"]').click();
    await page.click('.settings-button');
    await page.locator('#speech-provider').waitFor();
    assert.equal(await page.locator('#speech-provider').inputValue(), 'local');
    assert.equal(await page.locator('#local-speech-endpoint').inputValue(), 'ws://127.0.0.1:9012/asr');
    assert.equal(await page.locator('#local-speech-model').inputValue(), 'my-low-memory-model');
    assert.match(await page.locator('#local-model-info').innerText(), /Paraformer 中英双语/);
    await page.fill('#local-speech-model', 'different-model');
    assert.equal(await page.locator('#local-model-info').getAttribute('data-known'), 'false');
    assert.doesNotMatch(await page.locator('#local-model-info').innerText(), /Paraformer 中英双语/);
    await page.fill('#local-speech-model', 'my-low-memory-model');
    await page.fill('#local-speech-endpoint', 'ws://127.0.0.1:9013/asr');
    assert.equal(await page.locator('#local-model-info').getAttribute('data-known'), 'false');
    await page.fill('#local-speech-endpoint', 'ws://127.0.0.1:9012/asr');
    await page.locator('#local-speech-model').scrollIntoViewIfNeeded();
    await page.screenshot({ path: resolve(output, `${skin}.png`) });
    await page.locator('[data-model-id="paraformer-streaming-int8"] [data-action="switch-local-model"]').click();
    await page.waitForSelector('.local-model-option[data-model-id="paraformer-streaming-int8"][data-current="true"]');
    assert.equal(await page.locator('#local-speech-endpoint').inputValue(), 'ws://127.0.0.1:8765/asr');
    assert.equal(await page.locator('#local-speech-model').inputValue(), 'default');
    assert.match(await page.locator('#connection-result').innerText(), /已切换/);
    await page.locator('#local-model-recommendations').scrollIntoViewIfNeeded();
    await page.screenshot({ path: resolve(output, `${skin}-model-switch.png`) });
    await page.selectOption('#speech-provider', 'dashscope');
    assert.equal(await page.locator('#speech-model').inputValue(), cloudModel);
    assert.equal(await page.locator('#speech-endpoint').inputValue(), cloudEndpoint);
    assert.equal(await page.locator('#local-speech-fields').isVisible(), false);
    assert.deepEqual(errors, []);
    console.log(`PASS ${skin}: independent settings, full generic and targeted prompts, model metadata, cached reopen, invalidation, registered model switch and unregistered disabled`);
    await page.close();
  }
} finally {
  await browser.close();
  await server.close();
}
